#!/usr/bin/env node
// Pulls what the site needs from the Paths iOS repo, so the site never drifts
// from the app: design tokens, the Jost fonts, the app mark and artwork, the approved
// App Store copy, and the product documents the site's claims rest on.
//
//   npm run sync
//
// Everything written here is generated. Change it in the app repo, then sync.

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ios = resolve(process.env.PATHS_IOS_DIR ?? join(root, "..", "Paths"));

if (!existsSync(join(ios, "Paths.xcodeproj"))) {
  console.error(`Paths iOS repo not found at ${ios}. Set PATHS_IOS_DIR.`);
  process.exit(1);
}

const appCommit = spawnSync("git", ["-C", ios, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).stdout.trim();
const missing = [];

const copy = (from, to, banner) => {
  const source = join(ios, from);
  if (!existsSync(source)) return missing.push(from);
  mkdirSync(dirname(join(root, to)), { recursive: true });
  if (banner) writeFileSync(join(root, to), banner + readFileSync(source, "utf8"));
  else copyFileSync(source, join(root, to));
};

// --- Design tokens ----------------------------------------------------------

copy("tokens.css", "src/styles/app-tokens.css",
  `/* Generated by npm run sync from Paths/tokens.css. Do not edit here. */\n\n`);

// --- Fonts and mark ---------------------------------------------------------

// Jost, the typeface the app itself uses.
for (const style of ["Regular", "Italic", "Medium", "SemiBold", "Bold"]) {
  copy(`Paths/Fonts/Jost-${style}.ttf`, `public/fonts/Jost-${style}.ttf`);
}
copy("Paths/AppIcon.icon/Assets/P.svg", "src/assets/paths-mark.svg");

// --- App art ----------------------------------------------------------------

// The pictures the site shows outside the phone screens, all drawn for the app:
// the icons of its ready-made patterns, its calendar backgrounds and its badges.
// public/app and src/data/app-art.json are rebuilt whole on every sync.

const artDir = join(root, "public", "app");
rmSync(artDir, { recursive: true, force: true });

// takePictureMethod in the app is take-picture on the site.
const methodId = (method) => method.replace(/Method$/, "").replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

const templates = JSON.parse(readFileSync(join(ios, "Paths/Storage/Presets/Patterns/TemplatePatterns.json"), "utf8"));
const pattern = (item, archetype) => ({
  name: item.text, icon: basename(item.symbol), method: methodId(item.method), archetype,
});
const patterns = [
  ...Object.values(templates.shared).flat().map((item) => pattern(item, "shared")),
  ...Object.entries(templates.archetypes).flatMap(([archetype, sections]) =>
    Object.values(sections).flat().map((item) => pattern(item, archetype))),
];

// Icons from the app's set that the site uses on its own: one per method
// (src/content/methods.ts) and the tick in the plans.
const siteIcons = ["camera", "mic", "pen-line", "palette", "alarm-clock", "footprints", "arrow-up", "book",
  "grid-3x3", "check"];
for (const icon of new Set([...patterns.map((item) => item.icon), ...siteIcons])) {
  copy(`Paths/SVGAssets/lucide-icons/${icon}.svg`, `public/app/icons/${icon}.svg`);
}

// Which plan opens each calendar background, as the app assigns them.
const planOfTier = { 0: "free", 2: "plus", 3: "max" };
const assetCatalog = readFileSync(join(ios, "Paths/Models/Managers/SubscriptionAssetCatalog.swift"), "utf8");
const backgrounds = [];
for (const [, id, tier] of assetCatalog.matchAll(/"calendar:([^"]+)": (\d)/g)) {
  const source = `Paths/SVGAssets/background-assets/${id}.svg`;
  if (!planOfTier[tier] || !existsSync(join(ios, source))) { missing.push(source); continue; }
  copy(source, `public/app/backgrounds/${id}.svg`);
  backgrounds.push({ id, plan: planOfTier[tier] });
}

// The fifteen badges along the Progress road, in road order. The app's badge
// card carries its title and stars inside the picture, at sizes that differ from
// card to card, so the site takes the artwork alone, cropped to its coloured
// pixels, and sets the title in type, without the stars. Names, meanings and
// families come from Levels.swift: `BadgeLore` names each symbol and says what
// earning it means, `badgeCatalog` gives each badge its family and tier ("Study II").
const levelsSource = readFileSync(join(ios, "Paths/Models/Progress/Levels.swift"), "utf8");
const lore = new Map(
  [...levelsSource.matchAll(/(\d+): BadgeLoreEntry\(\s*symbolName: "([^"]+)",\s*origin: "[^"]*",\s*meaning: "([^"]+)"/g)]
    .map(([, number, name, meaning]) => [Number(number), { name, meaning }]));
const families = [...levelsSource.matchAll(/\("(\w+) (I{1,3})", \[/g)].map(([, family, tier]) => ({ family, tier: tier.length }));

const artworkBounds = async (source) => {
  const { data, info } = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width, top = info.height, right = -1, bottom = -1;
  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      const [red, green, blue, alpha] = data.subarray((y * info.width + x) * 4, (y * info.width + x) * 4 + 4);
      // The title and stars are black; only the artwork has colour.
      if (alpha <= 128 || Math.max(red, green, blue) - Math.min(red, green, blue) <= 14) continue;
      left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y);
    }
  }
  return right < 0 ? null : { left, top, width: right - left + 1, height: bottom - top + 1 };
};

const badges = [];
for (let number = 1; number <= 15; number += 1) {
  const name = `ProgressBadgeBlock${String(number).padStart(2, "0")}`;
  const source = join(ios, `Paths/Assets.xcassets/${name}.imageset/${name}.png`);
  const bounds = existsSync(source) ? await artworkBounds(source) : null;
  if (!bounds || !lore.has(number) || !families[number - 1]) { missing.push(name); continue; }
  const file = `/app/badges/badge-${String(number).padStart(2, "0")}.webp`;
  mkdirSync(join(artDir, "badges"), { recursive: true });
  const { width, height } = await sharp(source).extract(bounds)
    .resize(512, 512, { fit: "inside" }).webp({ quality: 86 }).toFile(join(root, "public", file));
  badges.push({ number, file, width, height, ...lore.get(number), ...families[number - 1] });
}

mkdirSync(join(root, "src", "data"), { recursive: true });
writeFileSync(join(root, "src", "data", "app-art.json"), JSON.stringify({
  _generated: "npm run sync, from the app's pattern templates, asset catalog and artwork. Do not edit here.",
  patterns, backgrounds, badges,
}, null, 2) + "\n");

// --- App Store copy ---------------------------------------------------------

const metadataDir = join(ios, "app_store", "metadata", "en-US");
const read = (name) => {
  const file = join(metadataDir, `${name}.txt`);
  return existsSync(file) ? readFileSync(file, "utf8").trim() : "";
};
const liveUrl = (value) => (value && !value.includes("REPLACE_WITH") ? value : null);

mkdirSync(join(root, "src", "content"), { recursive: true });
writeFileSync(join(root, "src", "content", "app-store.json"), JSON.stringify({
  _generated: "npm run sync, from Paths/app_store/metadata/en-US. Do not edit here.",
  subtitle: read("subtitle"),
  promotionalText: read("promotional_text"),
  description: read("description"),
  keywords: read("keywords").split(",").map((word) => word.trim()).filter(Boolean),
  privacyUrl: liveUrl(read("privacy_url")),
  supportUrl: liveUrl(read("support_url")),
  termsUrl: liveUrl(read("terms_url")),
}, null, 2) + "\n");

// --- Reference documents ----------------------------------------------------

const product = "docs/final-steps/product";
const documents = [
  `${product}/PATHS_APPLICATION_DOCUMENTATION.md`,
  `${product}/Paths_Design_Guide.md`,
  `${product}/ARETE_GREEK_ARCHETYPE_FRAMEWORK.md`,
  `${product}/ARCHETYPE_LEVEL_ENVIRONMENTS.md`,
  `${product}/METHODS_OVERVIEW.md`,
  `${product}/POINTS_SYSTEM.md`,
  `${product}/SUBSCRIPTIONS_AND_PROMOTIONS.md`,
  `${product}/PATHS_VERSION_ROADMAP.md`,
  "docs/final-steps/01-product-and-scope.md",
  "docs/final-steps/02-infrastructure-and-compliance.md",
  "Paths/Models/Learning/AretePersona.md",
];

const referenceDir = join(root, "reference");
if (existsSync(referenceDir)) {
  for (const file of readdirSync(referenceDir)) if (file !== "README.md") rmSync(join(referenceDir, file));
}
for (const document of documents) {
  copy(document, `reference/${basename(document)}`,
    `<!-- Copy of Paths/${document} at ${appCommit}. Generated by npm run sync. Do not edit here. -->\n\n`);
}

console.log(`Synced from ${ios} at ${appCommit}.`);
if (missing.length) {
  console.error(`Missing in the app repo:\n  ${missing.join("\n  ")}`);
  process.exit(1);
}
